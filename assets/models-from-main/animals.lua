-- วัดผลแล้ว: วัวได้สูง 4.5 · ม้า 5.2 · กวาง 6.8 (เขาสูงกว่าคน ซึ่งถูกแล้ว) · ไก่ 2.0
local LENGTH = {
	Chicken = 1.8, Duck = 2.0, Pig = 4.0, Goat = 4.0,
	Sheep = 4.5, Cow = 6.5, Deer = 5.5, Horse = 7.0,
}

local SHAPES = { [0] = Enum.PartType.Ball, [1] = Enum.PartType.Block, [2] = Enum.PartType.Cylinder }

-- คืน Model ของสัตว์ตัวเต็มวัย ฐานอยู่ที่ y = 0 · `GetScale()` ยังเป็น 1 (ดูหมายเหตุข้างบน)
return function(kind)
	local rows = DATA[kind]
	if not rows then return nil end

	-- หาความยาวจริงของต้นแบบก่อน แล้วค่อยรู้ว่าต้องคูณเท่าไหร่
	local lo, hi
	for _, row in ipairs(rows) do
		local half = Vector3.new(row[3], row[4], row[5]) / 2
		local at = Vector3.new(row[6], row[7], row[8])
		lo = lo and lo:Min(at - half) or (at - half)
		hi = hi and hi:Max(at + half) or (at + half)
	end
	local span = hi - lo
	local longest = math.max(span.X, span.Z)
	local scale = (LENGTH[kind] or 4) / math.max(longest, 0.01)

	local model = Instance.new("Model")
	model.Name = "Animal_" .. kind
	for _, row in ipairs(rows) do
		local shape = row[2]
		-- `Root` ของโรงงานเป็นหมุดล่องหน — `finish()` สร้างของมันเอง (บทเรียนเดียวกับเฟอร์นิเจอร์)
		if row[1] ~= "Root" and row[1] ~= "HumanoidRootPart" then
			local part = Instance.new(shape == 9 and "WedgePart" or "Part")
			part.Name = row[1]
			if shape ~= 9 and SHAPES[shape] then part.Shape = SHAPES[shape] end
			part.Size = Vector3.new(row[3], row[4], row[5]) * scale
			part.CFrame = CFrame.new(row[6] * scale, (row[7] - lo.Y) * scale, row[8] * scale,
				row[9], row[10], row[11], row[12], row[13], row[14], row[15], row[16], row[17])
			part.Color = Color3.fromRGB(bit32.band(bit32.rshift(row[18], 16), 255),
				bit32.band(bit32.rshift(row[18], 8), 255), bit32.band(row[18], 255))
			local ok = pcall(function() part.Material = Enum.Material[row[19]] end)
			if not ok then part.Material = Enum.Material.Plastic end
			part.Transparency = row[20]
			part.Reflectance = row[21]
			part.CanCollide = row[22] == 1
			part.Anchored = true
			part.Parent = model
		end
	end
	if #model:GetChildren() == 0 then model:Destroy() return nil end
	return model
end
