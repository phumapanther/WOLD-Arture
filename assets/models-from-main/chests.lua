local SHAPES = { [0] = Enum.PartType.Ball, [1] = Enum.PartType.Block, [2] = Enum.PartType.Cylinder }

-- สร้างหีบขึ้นใหม่ · ไม่มี scale: หีบในเกมหลักกับบนเกาะต้องขนาดเท่ากัน (มันคือไอเทมชิ้นเดียวกัน
-- ที่เดินข้ามเพลสมาในกระเป๋า ไม่ใช่ของตกแต่งที่ย่อตามสเกลบ้าน)
return function(name)
	local rows = DATA[name]
	if not rows then return nil end

	local model = Instance.new("Model")
	model.Name = name
	local root
	for _, row in ipairs(rows) do
		local shape = row[2]
		local part = Instance.new(shape == 9 and "WedgePart" or shape == 10 and "CornerWedgePart" or "Part")
		part.Name = row[1]
		if shape ~= 9 and shape ~= 10 and SHAPES[shape] then part.Shape = SHAPES[shape] end
		part.Size = Vector3.new(row[3], row[4], row[5])
		part.CFrame = CFrame.new(row[6], row[7], row[8],
			row[9], row[10], row[11], row[12], row[13], row[14], row[15], row[16], row[17])
		part.Color = Color3.fromRGB(bit32.band(bit32.rshift(row[18], 16), 255),
			bit32.band(bit32.rshift(row[18], 8), 255), bit32.band(row[18], 255))
		local ok = pcall(function() part.Material = Enum.Material[row[19]] end)
		if not ok then part.Material = Enum.Material.Plastic end
		part.Transparency = row[20]
		part.Reflectance = row[21]
		part.CanCollide = row[22] == 1
		part.Anchored = true
		part.Parent = model
		if part.Name == "Root" then root = part end
	end

	-- `Root` คือ PrimaryPart ของต้นฉบับ และทุกชิ้นถูกดัมพ์เทียบจุดหมุนเดิม — คืนทั้งสองอย่างให้ตรง
	-- ไม่งั้น `PivotTo` ของ `spawnChest` จะวางหีบผิดระดับ (`WorldPivot` ของ Model ที่สร้างใหม่มั่ว)
	model.PrimaryPart = root or model:FindFirstChildWhichIsA("BasePart")
	model.WorldPivot = CFrame.new()
	return model
end
