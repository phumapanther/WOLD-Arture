local SHAPES = { [0] = Enum.PartType.Ball, [1] = Enum.PartType.Block, [2] = Enum.PartType.Cylinder }

-- สร้างโมเดลขึ้นใหม่จากข้อมูล · `scale` คือตัวคูณ (เกาะย่อบ้าน 0.6 เฟอร์นิเจอร์ต้องย่อตามให้สัดส่วนคงเดิม)
-- ฐานถูกวางที่ y = 0 ตามกติกาของต้นแบบทุกตัวใน `90_island_placeables`
return function(name, scale)
	local rows = DATA[name]
	if not rows then return nil end
	scale = scale or 1

	local model = Instance.new("Model")
	model.Name = name
	local lowest = math.huge
	for _, row in ipairs(rows) do
		local shape = row[2]
		-- ⚠️ **ทิ้งชิ้น `Root` ที่ติดมาจากโรงงาน** มันคือหมุดล่องหน 1x1x1 ที่จุดกำเนิด ซึ่งบนเกาะเป็นหน้าที่
		-- ของ `finish()` — ปล่อยไว้แล้วพังสองทาง: มันเป็นชิ้นต่ำสุด (ก้น -0.5) ทั้งก้อนเลยถูกยกลอยพ้นพื้น
		-- ตามไปด้วย และ `finish()` เจอชื่อ `Root` ก็เอาไปเป็น PrimaryPart แล้วย้ายไปกึ่งกลางกล่อง
		if row[1] ~= "Root" then
			local part = Instance.new(shape == 9 and "WedgePart" or "Part")
			part.Name = row[1]
			if shape ~= 9 and SHAPES[shape] then part.Shape = SHAPES[shape] end
			part.Size = Vector3.new(row[3], row[4], row[5]) * scale
			local cf = CFrame.new(row[6] * scale, row[7] * scale, row[8] * scale,
				row[9], row[10], row[11], row[12], row[13], row[14], row[15], row[16], row[17])
			part.CFrame = cf
			part.Color = Color3.fromRGB(bit32.band(bit32.rshift(row[18], 16), 255),
				bit32.band(bit32.rshift(row[18], 8), 255), bit32.band(row[18], 255))
			local ok = pcall(function() part.Material = Enum.Material[row[19]] end)
			if not ok then part.Material = Enum.Material.Plastic end
			part.Transparency = row[20]
			part.Reflectance = row[21]
			part.CanCollide = row[22] == 1
			part.Anchored = true
			part.Parent = model
			lowest = math.min(lowest, (cf.Position.Y) - part.Size.Y / 2)
		end
	end
	if lowest == math.huge then model:Destroy() return nil end

	-- ยกทั้งก้อนให้ฐานอยู่ที่ y = 0 · ใช้ CFrame ตรงๆ เพราะยังไม่มี PrimaryPart ให้ PivotTo อ้างอิง
	for _, p in ipairs(model:GetChildren()) do
		if p:IsA("BasePart") then p.CFrame = p.CFrame + Vector3.new(0, -lowest, 0) end
	end
	return model
end
