--
-- ⚠️ **ปาร์ตี้ไม่เดินทางข้ามเพลส** `Party.lua` เป็นสถานะในหน่วยความจำของเซิร์ฟที่มันอยู่ ปาร์ตี้ที่ตั้งกัน
-- ในล็อบบี้จึงไม่มีอยู่ในเซิร์ฟแมตช์เลย — ด่าน "ตีกันเองไม่ได้" ในสนามต้องมาจากทีมของแมตช์ ไม่ใช่จากตี้
ArenaAccess.Friendly = nil

-- ตั้งโดย `Arena/ArenaMatch.server` · (attacker, victim, amount) เรียกทุกครั้งที่ดาเมจเข้าจริง
--
-- ระบบแมตช์เก็บยอดดาเมจและ**จำว่าใครตีคนนี้เป็นคนสุดท้าย**ไว้ที่นี่ เพราะจังหวะที่คนตายจริง
-- (`Humanoid.Died`) ไม่มีใครถือข้อมูลว่าใครเป็นคนทำอีกแล้ว
