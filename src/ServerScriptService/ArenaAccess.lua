ArenaAccess.TrapsAllowed = nil

-- ตั้งโดย `Arena/ArenaMatch.server` · () → true เฉพาะช่วงสู้ (ผู้ใช้สั่ง 2026-10-02) · ช่วงเตรียมตัว/นับถอยหลัง
