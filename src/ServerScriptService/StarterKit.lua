-- ผู้ใช้กำหนด: เครื่องมือครบสามอย่าง คันเบ็ด ขนมปังหนึ่งสแตค จักรยานล้อเดียว — **ไม่มีอาวุธ/เกราะ** (ต้องคราฟหรือหาเอง)
-- ⚠️ ก่อน 2026-09-25 มี TEST_GRANT แจกอาวุธ 4 เกราะ 3 ให้ผู้เล่นใหม่ตอนเข้าครั้งที่สอง ทำให้การคราฟไม่มีความหมาย —
-- ห้ามเพิ่มของต่อสู้ลงรายการนี้โดยไม่ถามผู้ใช้
local StarterKit = {}

StarterKit.Items = {
	-- ให้เครื่องมือครบทั้งสามเพราะการเก็บเกี่ยวบังคับว่าต้องมีเครื่องมือให้ตรงชนิด คนเข้าใหม่ไม่มีเงินและไม่มีทางหาได้เลย
	{ id = "Axe", count = 1 },
	{ id = "Shovel", count = 1 },
	{ id = "Pickaxe", count = 1 },
	{ id = "FishingRod", count = 1 },
	{ id = "Bread", count = 16 },
	-- จักรยานล้อเดียว แจกทุกคนตั้งแต่เริ่ม ตามที่ผู้ใช้สั่ง
	{ id = "Monowheel", count = 1 },
}

-- ได้ของเปิดตัวไหม — **ครั้งเดียวต่อบัญชีตลอดไป** (QA 2026-09-26)
-- `data` = profile.Data (nil = โหลดไม่สำเร็จ) · `saved` = data.Inventory ที่เซฟไว้
-- เดิมดูแค่ `data.Position` ซึ่งเซฟเฉพาะเมืองหลักตอนมีตัวละคร: ออกเร็วก่อนพิกัดถูกเซฟ = ได้ชุดใหม่ทุกครั้ง และคนที่เข้าเกาะ
-- เป็นที่แรก (แจก VIP ในล็อบบี้) ได้ชุดทุกครั้งที่เข้าเกาะ · บัญชีเก่าก่อนมีธง: มีกระเป๋าหรือพิกัด = เคยเล่นแล้ว
-- โหลดโปรไฟล์ไม่สำเร็จไม่ใช่คนใหม่ — ไม่มีที่ให้จดว่าแจกแล้ว แจกไปก็ได้ซ้ำทุกครั้ง
function StarterKit.ShouldGive(data, saved)
	if data == nil then return false end
	if data.StarterKit == true then return false end
	if saved ~= nil or data.Position ~= nil then return false end
	return true
end

return StarterKit
