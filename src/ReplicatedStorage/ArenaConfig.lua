-- ⚠️ **เซิร์ฟแมตช์ไม่เปิดเซสชันโปรไฟล์ของใครเลย** (`06-modes-build-plan.md` §4.3 เตือนไว้ว่าถ้าเผลอ
-- โหลดโปรไฟล์เต็มแล้วเซฟตอนจบ กระเป๋าจริงของคนเล่นจะถูกทับด้วยของในแมตช์) — รางวัลจึงถูก **ฝากไว้**
-- ใน DataStore แล้วเกมหลักมารับเองตอนคนนั้นเข้าเกมครั้งถัดไป ดู `Arena/ArenaRewards.lua`
--
-- `chest` คือระดับหีบที่จะได้ · อันดับตัดสินจากคะแนนผลงาน (คิล/ดาเมจ) ไม่ใช่จากทีมที่ชนะอย่างเดียว
ArenaConfig.Rewards = {
	-- เงินในเกมหลัก "เล็กน้อย" ตามที่ผู้ใช้สั่ง — ทั้งสองฝ่ายได้ ฝ่ายชนะได้มากกว่า
	goldWin = 120,
	goldLoss = 50,
	goldPerKill = 8,
	-- **EXP ของเกมหลัก** (ผู้ใช้สั่ง 2026-09-24) ฝากกลับทางเดียวกับเงิน/หีบ · ตัวเลขผมตั้งเอง ผู้ใช้ยังไม่ได้กำหนด
	expWin = 300,
	expLoss = 150,
	expPerKill = 25,
	-- หีบตามอันดับในตารางจบเกม (1 = อันดับหนึ่งของทั้งหกคน)
	-- ภาพม็อกอัพของผู้ใช้: อันดับ 1 หีบเวทมนตร์ · กลางๆ หีบทอง/หีบเหล็ก · ท้ายตาราง หีบไม้
	chestByRank = {
		-- อันดับ 1 = **กล่องเวทมนตร์** (`MagicBox`) กดใช้แล้วได้ของทันที ไม่ต้องมีโมเดลหีบ (ผู้ใช้สั่ง 2026-09-24)
		-- เดิมเป็น Chest_Magic ซึ่งต้องวางหีบลงพื้นก่อน และยังไม่มีโมเดล = กดใช้แล้วไม่เกิดอะไร
		[1] = "MagicBox",
		[2] = "Chest_Gold",
		[3] = "Chest_Gold",
		[4] = "Chest_Ironbound",
		[5] = "Chest_Ironbound",
		[6] = "Chest_Wood",
	},
	chestFallback = "Chest_Wood",
}

-- คะแนนผลงานที่ใช้จัดอันดับในตารางจบเกม — คิลหนักกว่าดาเมจ แต่ดาเมจไม่ใช่ศูนย์
-- (คนที่ตีจนใกล้ตายแล้วเพื่อนเก็บ ไม่ควรอยู่อันดับเดียวกับคนที่ยืนดู)
function ArenaConfig.Score(stat)
	return (stat.kills or 0) * 100 + (stat.assists or 0) * 40 + (stat.damage or 0) * 0.1 - (stat.deaths or 0) * 10
end

return ArenaConfig
