-- ClanConfig: กติกาของแคลน เป็นข้อมูลล้วน
--
-- แยกออกมาเหมือน ShopConfig และ CraftConfig ด้วยเหตุผลเดียวกัน: ตัวเลขทุกตัวที่อาจอยากปรับ อยู่ที่นี่
-- ที่เดียว และไคลเอนต์อ่านได้โดยไม่ต้องถามเซิร์ฟเวอร์
local ClanConfig = {}

--------------------------------------------------------------------------------
-- ตำแหน่งในแคลน
--------------------------------------------------------------------------------

-- เรียงจากใหญ่ไปเล็ก `rank` ยิ่งน้อยยิ่งใหญ่ — เทียบด้วยตัวเลขได้ตรงๆ ไม่ต้องมีตารางลำดับอีกชุด
ClanConfig.Roles = {
	{ id = "leader", name = "หัวแคลน", rank = 1 },
	{ id = "officer", name = "รองหัว", rank = 2 },
	{ id = "elder", name = "เสนา", rank = 3 },
	{ id = "member", name = "สมาชิก", rank = 4 },
}

function ClanConfig.RoleName(id)
	for _, r in ipairs(ClanConfig.Roles) do
		if r.id == id then return r.name end
	end
	return id
end

function ClanConfig.RankOf(id)
	for _, r in ipairs(ClanConfig.Roles) do
		if r.id == id then return r.rank end
	end
	return 99
end

--------------------------------------------------------------------------------
-- ข้อจำกัด
--------------------------------------------------------------------------------

ClanConfig.MaxMembers = 30
ClanConfig.NameMinLength = 3
ClanConfig.NameMaxLength = 18
ClanConfig.BlurbMaxLength = 200

-- ค่าสร้างแคลน จ่ายเป็นเหรียญซิลเวอร์
--
-- **ตั้งให้แพงพอที่แคลนจะไม่ใช่ของเล่น** ถ้าสร้างฟรี ทุกคนจะสร้างของตัวเองแล้วไม่มีใครรวมกลุ่มกันเลย
-- ซึ่งทำลายจุดประสงค์ทั้งหมดของระบบ
ClanConfig.CreateCostSilver = 500

-- คลังของแคลน
ClanConfig.VaultSlots = 40

-- เรทแปลงซิลเวอร์ในคลังเป็นเงินในเกมตอนแจกจ่าย ผู้ใช้กำหนด 1 ต่อ 1
ClanConfig.SilverToGold = 1

--------------------------------------------------------------------------------
-- ยึดเมือง (เตรียมไว้ให้รอบถัดไป)
--------------------------------------------------------------------------------

-- กดค้างกี่วินาทีถึงจะยึดได้ ผู้ใช้กำหนดราว 59
ClanConfig.CaptureSeconds = 59

-- ยึดแล้วต้องไม่มีใครมาแย่งภายในกี่วินาที ถึงจะเป็นของจริง
ClanConfig.ContestSeconds = 30 * 60

-- ทำเควสในเมืองที่แคลนตัวเองยึดอยู่ ได้ซิลเวอร์คูณเท่านี้
ClanConfig.QuestSilverMultiplier = 2

-- ภาษีที่หักเข้าคลังแคลนเมื่อมีคนขายของกับ NPC ประจำเมือง
ClanConfig.TaxFraction = 0.1

-- ส่วนลด/ราคาที่ดีขึ้นสำหรับคนในแคลนที่ยึดเมืองนั้น
ClanConfig.HomeSellBonus = 0.25

return ClanConfig
